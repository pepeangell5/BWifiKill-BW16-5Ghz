static uint16_t splashStrWidth(Adafruit_ST7735 &tft, const char *txt) {
  int16_t x1, y1; uint16_t w, h;
  tft.getTextBounds(txt, 0, 0, &x1, &y1, &w, &h);
  return w;
}

void splashDraw(Adafruit_ST7735 &tft) {
  tft.fillScreen(UI_BG);
  tft.drawRoundRect(2, 2, tft.width() - 4, tft.height() - 4, 6, UI_LINE);

  // Bitmap del ajolote
  int iconX = (tft.width() - AJOLOTE_WIDTH) / 2;
  int iconY = 6;
  tft.drawBitmap(iconX, iconY, AJOLOTE_BMP, AJOLOTE_WIDTH, AJOLOTE_HEIGHT, UI_BRAND);

  // Titulo "BWifiKill" - tamano normal, no x2
  tft.setFont(&FreeSansBold9pt7b);
  tft.setTextSize(1);
  tft.setTextColor(UI_DANGER);
  const char *title = "BWifiKill";
  uint16_t tw = splashStrWidth(tft, title);
  tft.setCursor((tft.width() - tw) / 2, 108);
  tft.print(title);

  // Subtitulo con fuente default
  tft.setFont(NULL);
  tft.setTextSize(1);
  tft.setTextColor(UI_TEXT_DIM);
  const char *sub = "BW16  2.4 / 5GHz";
  uint16_t sw = strlen(sub) * 6;
  tft.setCursor((tft.width() - sw) / 2, 122);
  tft.print(sub);

  // Chip
  tft.setFont(&Picopixel);
  tft.setTextColor(UI_MUTED);
  const char *chip = "RTL8720DN";
  uint16_t cw = splashStrWidth(tft, chip);
  tft.setCursor((tft.width() - cw) / 2, 140);
  tft.print(chip);

  tft.setFont(NULL);
}